//! Streaming synthesis output types ([`StageTimings`], [`AudioChunk`], [`SynthesisResult`],
//! and [`SynthesisStream`]).

use std::path::Path;

use flume::Receiver;
use serde::{Deserialize, Serialize};

use crate::{
    dsp::{encode_wav_i16_bytes, write_wav_i16_file},
    error::Result,
};

/// Detailed wall-clock timing breakdown (in milliseconds) across pipeline stages.
#[derive(Debug, Default, Clone, Copy, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
#[non_exhaustive]
pub struct StageTimings {
    /// Stage 0 reference voice extraction time in milliseconds (`0.0` when using a cached
    /// `.itts_voice` snapshot).
    pub voice_extract_ms: f64,
    /// Text normalization, BPE tokenization, and sentence segmentation time in milliseconds.
    pub frontend_ms: f64,
    /// Stage 1 Int8 GPT autoregressive code generation time in milliseconds.
    pub gpt_ms: f64,
    /// Stage 2 `SemanticCodec` VQ decode + `ConvNeXt` + 2x upsample time in milliseconds.
    pub codec_ms: f64,
    /// Stage 2 `LengthRegulator` nearest-neighbor interpolation + Conv1d stack time in ms.
    pub regulator_ms: f64,
    /// Stage 2 `CfmDit` 25-step Euler ODE solver time in milliseconds.
    pub cfm_ms: f64,
    /// Stage 3 `BigVgan` 256x neural vocoder time in milliseconds.
    pub bigvgan_ms: f64,
    /// Total end-to-end wall-clock latency in milliseconds.
    pub total_ms: f64,
}

impl StageTimings {
    /// Accumulates per-segment synthesis timings from `other` into `self`.
    pub fn accumulate_segment(&mut self, other: &Self) {
        self.voice_extract_ms += other.voice_extract_ms;
        self.frontend_ms += other.frontend_ms;
        self.gpt_ms += other.gpt_ms;
        self.codec_ms += other.codec_ms;
        self.regulator_ms += other.regulator_ms;
        self.cfm_ms += other.cfm_ms;
        self.bigvgan_ms += other.bigvgan_ms;
    }
}

/// A single synthesized sentence segment emitted by [`SynthesisStream`].
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
#[non_exhaustive]
pub struct AudioChunk {
    /// Zero-based index of the current sentence segment (`0..total_segments`).
    pub segment_index: usize,
    /// Total number of sentence segments in the synthesis request.
    pub total_segments: usize,
    /// 22,050 Hz mono 16-bit signed PCM samples for this segment.
    pub pcm_i16: Vec<i16>,
    /// Output sample rate in Hz (`22050`).
    pub sample_rate: u32,
    /// Number of discrete Mel semantic codes generated by Stage 1 GPT for this segment.
    pub mel_tokens: usize,
    /// Per-stage timing breakdown for this segment.
    pub timings: StageTimings,
}

impl AudioChunk {
    /// Returns the audio duration of this chunk in seconds.
    ///
    /// # Examples
    ///
    /// ```
    /// use index_tts_rs_core::engine::{AudioChunk, StageTimings};
    ///
    /// let chunk = AudioChunk::new(0, 1, vec![0_i16; 22050], 22050, 50, StageTimings::default());
    /// assert!((chunk.duration_secs() - 1.0).abs() < 1e-5);
    /// ```
    #[must_use]
    pub fn new(
        segment_index: usize,
        total_segments: usize,
        pcm_i16: Vec<i16>,
        sample_rate: u32,
        mel_tokens: usize,
        timings: StageTimings,
    ) -> Self {
        Self {
            segment_index,
            total_segments,
            pcm_i16,
            sample_rate,
            mel_tokens,
            timings,
        }
    }

    /// Returns the duration of this segment's PCM buffer in seconds.
    #[must_use]
    #[allow(clippy::cast_precision_loss)]
    pub fn duration_secs(&self) -> f32 {
        if self.sample_rate == 0 {
            return 0.0;
        }
        (self.pcm_i16.len() as f32) / (self.sample_rate as f32)
    }
}

/// Complete end-to-end speech synthesis output across all sentence segments.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
#[non_exhaustive]
pub struct SynthesisResult {
    /// Concatenated 22,050 Hz mono 16-bit signed PCM samples (including inter-segment silence).
    pub pcm_i16: Vec<i16>,
    /// Output sample rate in Hz (`22050`).
    pub sample_rate: u32,
    /// Total synthesized audio duration in seconds.
    pub duration_secs: f32,
    /// Total end-to-end synthesis wall-clock time in seconds.
    pub synthesis_secs: f32,
    /// Real-time factor (`synthesis_secs / duration_secs`; `< 1.0` means faster than real-time).
    pub rtf: f32,
    /// Number of synthesized sentence segments.
    pub segments_count: usize,
    /// Total number of discrete Mel tokens generated across all segments.
    pub total_mel_tokens: usize,
    /// Cumulative per-stage timing breakdown.
    pub timings: StageTimings,
}

/// Alias for [`SynthesisResult`].
pub type SynthesisOutput = SynthesisResult;

impl SynthesisResult {
    /// Constructs a new [`SynthesisResult`].
    #[must_use]
    #[allow(clippy::cast_precision_loss)]
    pub fn new(
        pcm_i16: Vec<i16>,
        sample_rate: u32,
        synthesis_secs: f32,
        segments_count: usize,
        total_mel_tokens: usize,
        timings: StageTimings,
    ) -> Self {
        let duration_secs = if sample_rate == 0 {
            0.0
        } else {
            (pcm_i16.len() as f32) / (sample_rate as f32)
        };
        let rtf = if duration_secs > 1e-6 {
            synthesis_secs / duration_secs
        } else {
            0.0
        };
        Self {
            pcm_i16,
            sample_rate,
            duration_secs,
            synthesis_secs,
            rtf,
            segments_count,
            total_mel_tokens,
            timings,
        }
    }

    /// Encodes the synthesized PCM waveform into an in-memory 16-bit mono WAV byte buffer.
    ///
    /// # Errors
    ///
    /// Returns [`IndexTtsError::AudioEncode`](crate::error::IndexTtsError::AudioEncode) if WAV
    /// serialization fails.
    ///
    /// # Examples
    ///
    /// ```
    /// use index_tts_rs_core::engine::{StageTimings, SynthesisResult};
    ///
    /// let res = SynthesisResult::new(vec![0_i16; 2205], 22050, 0.02, 1, 10, StageTimings::default());
    /// let wav = res.to_wav_bytes()?;
    /// assert!(wav.starts_with(b"RIFF"));
    /// # Ok::<(), index_tts_rs_core::error::IndexTtsError>(())
    /// ```
    pub fn to_wav_bytes(&self) -> Result<Vec<u8>> {
        encode_wav_i16_bytes(&self.pcm_i16, self.sample_rate)
    }

    /// Writes the synthesized PCM waveform to a `.wav` file on disk.
    ///
    /// # Errors
    ///
    /// Returns [`IndexTtsError`](crate::error::IndexTtsError) if the path is invalid or writing
    /// fails.
    pub fn save_wav(&self, path: impl AsRef<Path>) -> Result<()> {
        write_wav_i16_file(path, &self.pcm_i16, self.sample_rate)
    }
}

/// Receiver stream yielding [`AudioChunk`]s sentence-by-sentence as the GPU worker finishes each
/// segment.
///
/// Dropping [`SynthesisStream`] disconnects the underlying channel, signaling the
/// `MlxWorkerActor` to cancel any remaining ungenerated sentence segments immediately.
#[derive(Debug)]
pub struct SynthesisStream {
    rx: Receiver<Result<AudioChunk>>,
}

impl SynthesisStream {
    /// Wraps a `flume::Receiver<Result<AudioChunk>>` into a [`SynthesisStream`].
    #[must_use]
    pub const fn new(rx: Receiver<Result<AudioChunk>>) -> Self {
        Self { rx }
    }

    /// Blocks the current thread until the next [`AudioChunk`] is ready or the stream ends.
    #[must_use]
    pub fn recv(&self) -> Option<Result<AudioChunk>> {
        self.rx.recv().ok()
    }

    /// Asynchronously awaits the next [`AudioChunk`] without blocking the Tokio executor.
    ///
    /// # Examples
    ///
    /// ```
    /// use index_tts_rs_core::engine::{AudioChunk, StageTimings, SynthesisStream};
    ///
    /// let rt = tokio::runtime::Runtime::new().unwrap();
    /// rt.block_on(async {
    ///     let (tx, rx) = flume::bounded(2);
    ///     tx.send(Ok(AudioChunk::new(0, 1, vec![0; 100], 22050, 5, StageTimings::default()))).unwrap();
    ///     drop(tx);
    ///     let stream = SynthesisStream::new(rx);
    ///     let chunk = stream.next_chunk().await.unwrap().unwrap();
    ///     assert_eq!(chunk.segment_index, 0);
    ///     assert!(stream.next_chunk().await.is_none());
    /// });
    /// ```
    pub async fn next_chunk(&self) -> Option<Result<AudioChunk>> {
        self.rx.recv_async().await.ok()
    }
}

impl Iterator for SynthesisStream {
    type Item = Result<AudioChunk>;

    fn next(&mut self) -> Option<Self::Item> {
        self.recv()
    }
}
